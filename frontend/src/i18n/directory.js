export function getTranslation(lang, key) {
  const keys = key.split('.');
  let value = translations[lang] || translations.de;
  
  for (const k of keys) {
    value = value[k];
    if (!value) return key;
  }
  
  return value;
}

export function useTranslation(lang = 'de') {
  return (key) => getTranslation(lang, key);
}
